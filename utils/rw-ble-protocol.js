function queryCrc16(crc16, value) {
  return (crc16 >>> 8) ^ CRC_TABLE[(crc16 ^ value) & 0xff]
}

export function calculateCrc16(bytes) {
  let crc16 = 0
  for (let i = 0; i < bytes.length; i += 1) crc16 = queryCrc16(crc16, bytes[i])
  return crc16 & 0xffff
}

export function buildPacket(dataBytes, flag = FLAG_WRITE) {
  const data = dataBytes instanceof Uint8Array ? dataBytes : new Uint8Array(dataBytes || [])
  const crc = calculateCrc16(data)
  const out = new Uint8Array(6 + data.length)
  out[0] = HEADER
  out[1] = flag
  out[2] = (data.length >> 8) & 0xff
  out[3] = data.length & 0xff
  out[4] = (crc >> 8) & 0xff
  out[5] = crc & 0xff
  out.set(data, 6)
  return out.buffer
}

export function parsePacket(buffer) {
  const bytes = new Uint8Array(buffer)
  if (bytes.length < 6 || bytes[0] !== HEADER) return null
  const len = (bytes[2] << 8) | bytes[3]
  if (bytes.length < 6 + len) return null
  const crc = (bytes[4] << 8) | bytes[5]
  const data = bytes.slice(6, 6 + len)
  return { flag: bytes[1], len, crc, data, crcOk: calculateCrc16(data) === crc }
}

export function parseCmdData(dataBytes) {
  if (!dataBytes || dataBytes.length < 3) return null
  return {
    cmd: dataBytes[0],
    key: dataBytes[1],
    keyFlag: dataBytes[2],
    value: dataBytes.slice(3)
  }
}

export function cmdData(cmd, key, keyFlag, value = []) {
  const arr = new Uint8Array(3 + value.length)
  arr[0] = cmd
  arr[1] = key
  arr[2] = keyFlag
  arr.set(value, 3)
  return arr
}

export function commandLogin() { return buildPacket(cmdData(0x03, 0x02, 0x20)) }
export function commandFindDevice(enable = true) { return buildPacket(cmdData(0x02, 0x34, 0x00, [enable ? 0x01 : 0x00])) }
export function commandSetTimezone(tzQuarterHours) { return buildPacket(cmdData(0x02, 0x02, 0x00, [tzQuarterHours & 0xff])) }
export function commandSetTime(date = new Date()) {
  const y = date.getFullYear() - 2000
  const v = [y & 0xff, date.getMonth() + 1, date.getDate(), date.getHours(), date.getMinutes(), date.getSeconds()]
  return buildPacket(cmdData(0x02, 0x01, 0x00, v))
}
export function commandStartSingleTest(dataTypeLE, continuous = false) {
  const lo = dataTypeLE & 0xff
  const hi = (dataTypeLE >> 8) & 0xff
  return buildPacket(cmdData(0x06, 0x09, 0x00, [lo, hi, 0x01, continuous ? 0x01 : 0x00]))
}
export function commandStopSingleTest(dataTypeLE) {
  const lo = dataTypeLE & 0xff
  const hi = (dataTypeLE >> 8) & 0xff
  return buildPacket(cmdData(0x06, 0x09, 0x00, [lo, hi, 0x00]))
}

export function commandReadHistory(dataType) {
  return buildPacket(cmdData(0x05, dataType, 0x10))
}

export function commandDeleteHistory(dataType) {
  return buildPacket(cmdData(0x05, dataType, 0x30))
}

